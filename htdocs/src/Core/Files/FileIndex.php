<?php

declare(strict_types=1);

namespace Dolibarr\Core\Files;

use Dolibarr\Core\Config;
use Dolibarr\Core\Database\Connection;
use Dolibarr\Core\Database\DatabaseException;
use Dolibarr\Core\Legacy\LegacyContext;
use Dolibarr\Core\Legacy\LegacyFileObjects;
use Dolibarr\Core\Legacy\LegacyTriggers;

/**
 * The file index llx_ecm_files, written as the legacy does it (addFileIntoDatabaseIndex, the index part of
 * dol_delete_file and dol_move, deleteFilesIntoDatabaseIndex, the share of actions_linkedfiles.inc.php) with the
 * ECMFILES_CREATE, ECMFILES_MODIFY and ECMFILES_DELETE triggers of \EcmFiles. Each write and its trigger share one
 * transaction: a trigger that fails undoes the row and raises FileTriggerException.
 *
 * The files themselves are not touched: the caller moves or deletes them.
 */
final class FileIndex
{
	/** addFileIntoDatabaseIndex(): not tested for the directory of a file in a temp folder, whose path has no ending slash */
	private const EXCLUDED_DIRECTORY = '/[\\/]temp[\\/]|[\\/]thumbs|\.meta$/';

	/** dol_move() */
	private const EXCLUDED_MOVED_FILE = '/([\\/]temp[\\/]|[\\/]thumbs|\.meta$)/';

	/** dol_delete_file() */
	private const EXCLUDED_DELETED_FILE = '/(\/temp\/|\/thumbs\/|\.meta$)/';

	public function __construct(
		private readonly EcmFileRepository $files,
		private readonly Connection $connection,
		private readonly LegacyTriggers $triggers,
		private readonly LegacyFileObjects $objects,
		private readonly Config $config,
		private readonly LegacyContext $context
	) {
	}

	/**
	 * Indexes an uploaded file (addFileIntoDatabaseIndex() with the mode 'uploaded', then EcmFiles::create()).
	 *
	 * @param string $directory       Full path of the directory (under DOL_DATA_ROOT, no ending slash)
	 * @param string $storedName      Name of the file on disk, possibly ending with .noexe
	 * @param string $originalName    Name of the file on the sender's side
	 * @param string $forceFullTextIndexation '1' to index the content as text even without MAIN_SAVE_FILE_CONTENT_AS_TEXT
	 * @return EcmFile|null           The new row, null for a temp, thumbs or .meta directory and when the content
	 *                                of a PDF cannot be converted
	 * @throws \InvalidArgumentException An empty directory or file name
	 * @throws \LogicException           Without a logged user, or if the trigger object cannot be loaded
	 * @throws FileTriggerException      A trigger failed, nothing is written
	 * @throws DatabaseException
	 */
	public function add(string $directory, string $storedName, string $originalName, ?\CommonObject $source, bool $share, string $forceFullTextIndexation = ''): ?EcmFile
	{
		$relativeDirectory = self::relative($directory);
		if (preg_match(self::EXCLUDED_DIRECTORY, $relativeDirectory) === 1) {
			return null;
		}
		$filename = self::cleanFilename(basename((string) preg_replace('/\.noexe$/', '', $storedName)));
		$filepath = self::cleanDirectory($relativeDirectory);
		if ($filename === '' || $filepath === '') {
			throw new \InvalidArgumentException('Bad property filename or filepath');
		}

		$entity = $this->config->entity();
		$sourceType = null;
		$sourceId = null;
		$description = '';
		$keywords = '';
		if ($source !== null && (int) $source->id > 0) {
			$sourceId = (int) $source->id;
			$sourceType = (string) $source->table_element;
			$sourceProperties = get_object_vars($source);
			$description = (string) ($sourceProperties['src_object_description'] ?? '');
			$keywords = (string) ($sourceProperties['src_object_keywords'] ?? '');
			if (isset($source->entity)) {
				$entity = (int) $source->entity;
			}
		}

		$shareKey = null;
		if ($share || self::enabled($this->config->string('MAIN_FORCE_SHARING_ON_ANY_UPLOADED_FILE'))) {
			require_once DOL_DOCUMENT_ROOT.'/core/lib/security2.lib.php';
			$shareKey = getRandomPassword(true);
		}

		$storeContent = self::enabled($this->config->string('MAIN_SAVE_FILE_CONTENT_AS_TEXT'));
		$content = null;
		$fullTextMode = $this->config->string('MAIN_SAVE_FILE_CONTENT_AS_TEXT');
		if (!self::enabled($fullTextMode) && $forceFullTextIndexation === '1') {
			if (self::enabled($this->config->string('MAIN_SAVE_FILE_CONTENT_AS_TEXT_PDFTOTEXT'))) {
				$fullTextMode = 'pdftotext';
			} elseif (self::enabled($this->config->string('MAIN_SAVE_FILE_CONTENT_AS_TEXT_DOCLING'))) {
				$fullTextMode = 'docling';
			}
		}
		if (self::enabled($fullTextMode)) {
			require_once DOL_DOCUMENT_ROOT.'/core/lib/files.lib.php';
			$text = '';
			$command = '';
			if (preg_match('/\.pdf/i', $filename) === 1) {
				$converted = dolDocToText($directory.'/'.$filename);
				if (!empty($converted['error'])) {
					return null;
				}
				$text = (string) $converted['content'];
				$command = (string) $converted['cmd'];
			}
			if ($command !== '') {
				$description = 'File content generated by '.$command;
			}
			$content = $storeContent ? $text : null;
			$keywords = '';
		}

		require_once DOL_DOCUMENT_ROOT.'/core/lib/security.lib.php';
		$now = new \DateTimeImmutable('now', new \DateTimeZone('UTC'));
		$actorId = (int) $this->actor()->id;
		$label = (string) md5_file(dol_osencode($directory.'/'.$storedName));

		return $this->connection->transactional(function () use ($filename, $filepath, $label, $originalName, $description, $keywords, $content, $entity, $sourceType, $sourceId, $shareKey, $now, $actorId): EcmFile {
			$saved = $this->files->save(new EcmFile(
				null,
				dol_hash($filepath.'/'.$filename, '3'),
				trim($label),
				$shareKey,
				$entity,
				$filepath,
				$filename,
				$sourceType,
				$sourceId,
				trim($originalName),
				trim($description),
				trim($keywords),
				$content,
				null,
				$this->files->nextPosition($filepath),
				'uploaded',
				null,
				$now,
				$now,
				$actorId
			));
			$this->fireTrigger('ECMFILES_CREATE', (int) $saved->id);

			return $saved;
		});
	}

	/**
	 * Removes the row of a deleted file, with ECMFILES_DELETE sent before the deletion (dol_delete_file()).
	 * Nothing for a temp, thumbs or .meta file or a file not indexed.
	 *
	 * @param string $absolutePath Full path of the file, possibly ending with .noexe
	 * @throws \LogicException      Without a logged user, or if the trigger object cannot be loaded
	 * @throws FileTriggerException The trigger failed, the row is kept
	 * @throws DatabaseException
	 */
	public function removeFile(string $absolutePath, int $entity): void
	{
		$relativePath = self::relative($absolutePath);
		if (preg_match(self::EXCLUDED_DELETED_FILE, $relativePath) === 1) {
			return;
		}
		$relativePath = (string) preg_replace('/\.noexe$/', '', (string) preg_replace('/^[\\/]/', '', $relativePath));

		$this->connection->transactional(function () use ($relativePath, $entity): void {
			$file = $this->files->findByPath($entity, dirname($relativePath), basename($relativePath));
			if ($file !== null) {
				$this->deleteRow($file);
			}
		});
	}

	/**
	 * Removes the rows of a directory, of one file or of all its files, without trigger (deleteFilesIntoDatabaseIndex()
	 * without a mode): the index of a file about to be written again.
	 *
	 * @param string $directory Full path of the directory (under DOL_DATA_ROOT)
	 * @param string $fileName  Name of the file, '' for every file of the directory
	 * @throws \InvalidArgumentException An empty directory
	 * @throws DatabaseException
	 */
	public function removeIndexRow(string $directory, string $fileName, int $entity): void
	{
		if ($directory === '') {
			throw new \InvalidArgumentException("The directory can't be empty");
		}
		$relativeDirectory = self::relative($directory);
		if (preg_match(self::EXCLUDED_DIRECTORY, $relativeDirectory) === 1) {
			return;
		}
		$filepath = self::cleanDirectory($relativeDirectory);

		$this->connection->transactional(function () use ($entity, $filepath, $fileName): void {
			if ($fileName !== '') {
				$this->connection->execute(
					'DELETE FROM @ecm_files WHERE entity = :entity AND filepath = :filepath AND filename = :filename',
					['entity' => $entity, 'filepath' => $filepath, 'filename' => $fileName]
				);
			} else {
				$this->connection->execute(
					'DELETE FROM @ecm_files WHERE entity = :entity AND filepath = :filepath',
					['entity' => $entity, 'filepath' => $filepath]
				);
			}
		});
	}

	/**
	 * Follows a moved file in the index (dol_move()): the row of an existing target is deleted (ECMFILES_DELETE), the
	 * row of the source takes the new path (ECMFILES_MODIFY) or, for a file the index does not know, a row is created
	 * with the mode 'unknown' (ECMFILES_CREATE). Nothing for a target in a temp, thumbs or .meta location.
	 *
	 * @param string $sourcePath Full path of the file before the move
	 * @param string $targetPath Full path of the file after the move: the file exists
	 * @throws \LogicException      Without a logged user, or if the trigger object cannot be loaded
	 * @throws FileTriggerException A trigger failed, no row is changed
	 * @throws DatabaseException
	 */
	public function rename(string $sourcePath, string $targetPath, int $entity): void
	{
		$relativeTarget = self::relative($targetPath);
		if (preg_match(self::EXCLUDED_MOVED_FILE, $relativeTarget) === 1) {
			return;
		}
		$relativeSource = (string) preg_replace('/^[\\/]/', '', self::relative($sourcePath));
		$relativeTarget = (string) preg_replace('/^[\\/]/', '', $relativeTarget);
		$targetDirectory = self::cleanDirectory(dirname($relativeTarget));
		$targetName = self::cleanFilename(basename($relativeTarget));
		require_once DOL_DOCUMENT_ROOT.'/core/lib/security.lib.php';
		$label = (string) md5_file(dol_osencode($targetPath));
		$now = new \DateTimeImmutable('now', new \DateTimeZone('UTC'));

		$this->connection->transactional(function () use ($sourcePath, $relativeSource, $relativeTarget, $targetDirectory, $targetName, $entity, $label, $now): void {
			$existingTarget = $this->files->findByPath($entity, dirname($relativeTarget), self::withoutNoexe(basename($relativeTarget)));
			if ($existingTarget !== null) {
				$this->deleteRow($existingTarget);
			}

			$source = $this->files->findByPath($entity, dirname($relativeSource), self::withoutNoexe(basename($relativeSource)));
			if ($source !== null) {
				$moved = $this->files->save($this->files->modify($source, [
					'filepath' => $targetDirectory,
					'filename' => $targetName,
					'ref' => dol_hash($targetDirectory.'/'.$targetName, '3'),
					'modifiedBy' => $this->modifier($source),
				]));
				$this->fireTrigger('ECMFILES_MODIFY', (int) $moved->id);

				return;
			}

			$created = $this->files->save(new EcmFile(
				null,
				dol_hash($targetDirectory.'/'.$targetName, '3'),
				trim($label),
				null,
				$entity > 0 ? $entity : $this->config->entity(),
				$targetDirectory,
				$targetName,
				null,
				null,
				trim(basename($sourcePath)),
				'',
				'',
				null,
				null,
				$this->files->nextPosition($targetDirectory),
				'unknown',
				null,
				$now,
				$now,
				(int) $this->actor()->id
			));
			$this->fireTrigger('ECMFILES_CREATE', (int) $created->id);
		});
	}

	/**
	 * Enables or disables the sharing of a file (actions_linkedfiles.inc.php): a new random key when enabling a file
	 * that has none, the key kept when already shared, no key (NULL) when disabling. The row is always updated and
	 * ECMFILES_MODIFY is always sent, as EcmFiles::update() is at each save of the form.
	 *
	 * @throws \LogicException      Without a logged user, or if the trigger object cannot be loaded
	 * @throws FileTriggerException The trigger failed, the row is unchanged
	 * @throws DatabaseException
	 */
	public function setShared(EcmFile $file, bool $enabled): EcmFile
	{
		$shareKey = null;
		if ($enabled) {
			$shareKey = trim((string) $file->share);
			if ($shareKey === '') {
				require_once DOL_DOCUMENT_ROOT.'/core/lib/security2.lib.php';
				$shareKey = getRandomPassword(true);
			}
		}
		require_once DOL_DOCUMENT_ROOT.'/core/lib/security.lib.php';

		return $this->connection->transactional(function () use ($file, $shareKey): EcmFile {
			$saved = $this->files->save($this->files->modify($file, [
				'share' => $shareKey,
				'ref' => dol_hash($file->filepath.'/'.$file->filename, '3'),
				'modifiedBy' => $this->modifier($file),
			]));
			$this->fireTrigger('ECMFILES_MODIFY', (int) $saved->id);

			return $saved;
		});
	}

	/**
	 * EcmFiles::delete(): the trigger, then the row (and its extra fields).
	 *
	 * @throws FileTriggerException
	 * @throws \LogicException
	 * @throws DatabaseException
	 */
	private function deleteRow(EcmFile $file): void
	{
		$this->fireTrigger('ECMFILES_DELETE', (int) $file->id);
		$this->files->delete($file);
	}

	/**
	 * EcmFiles::update() keeps the modifier already recorded and takes the current user only for a row never modified.
	 */
	private function modifier(EcmFile $file): int
	{
		return $file->modifiedBy !== null && $file->modifiedBy > 0 ? $file->modifiedBy : (int) $this->actor()->id;
	}

	/**
	 * @throws FileTriggerException
	 * @throws \LogicException
	 */
	private function fireTrigger(string $action, int $id): void
	{
		$object = $this->objects->ecmFile($id) ?? throw new \LogicException('The file index row '.$id.' cannot be loaded for the trigger '.$action);
		if ($this->triggers->run($action, $object, $this->actor()) < 0) {
			throw new FileTriggerException($this->triggers->errors());
		}
	}

	/**
	 * @throws \LogicException
	 */
	private function actor(): \User
	{
		return $this->context->user ?? throw new \LogicException('A trigger of the file index needs the logged legacy user');
	}

	/**
	 * The path relative to DOL_DATA_ROOT.
	 */
	private static function relative(string $path): string
	{
		return (string) preg_replace('/^'.preg_quote(DOL_DATA_ROOT, '/').'/', '', $path);
	}

	/**
	 * A relative directory as stored: no leading slash, no ending slash.
	 */
	private static function cleanDirectory(string $relativeDirectory): string
	{
		$directory = (string) preg_replace('/[\\/]$/', '', $relativeDirectory);
		$directory = (string) preg_replace('/^[\\/]/', '', $directory);

		return (string) preg_replace('/[\\/]+$/', '', trim($directory));
	}

	private static function cleanFilename(string $filename): string
	{
		return self::withoutNoexe(trim($filename));
	}

	private static function withoutNoexe(string $filename): string
	{
		return (string) preg_replace('/\.noexe$/', '', $filename);
	}

	/**
	 * PHP truthiness of a constant read as text ('' and '0' are off).
	 */
	private static function enabled(string $value): bool
	{
		return $value !== '' && $value !== '0';
	}
}
